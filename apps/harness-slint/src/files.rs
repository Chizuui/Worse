fn material_index(name: &str) -> i32 {
    MATERIAL
        .iter()
        .position(|m| *m == name)
        .and_then(|i| i32::try_from(i).ok())
        .unwrap_or(1)
}

/// Index into `FileIcons.all` for a file-tree entry (`ZCode` `fileDisplayHelpers.ts` rules, reduced to the
/// bundled icons; unknown types get the generic document icon).
pub fn icon_index(name: &str, is_dir: bool) -> i32 {
    if is_dir {
        return 0;
    }
    let lower = name.to_lowercase();
    let stem = lower
        .rsplit_once('.')
        .map_or(lower.as_str(), |(stem, _)| stem);
    if let Some((_, icon)) = NAME_ALIASES
        .iter()
        .find(|(alias, _)| *alias == lower || *alias == stem)
    {
        return material_index(icon);
    }
    lower
        .rsplit_once('.')
        .map_or(1, |(_, ext)| lang_icon_index(ext))
}

/// Index into `FileIcons.all` for a file extension or code-fence language (`rust`, `ts`, `sh`…).
pub fn lang_icon_index(lang: &str) -> i32 {
    let lower = lang.to_lowercase();
    EXT_ALIASES
        .iter()
        .find(|(ext, _)| *ext == lower)
        .map_or(1, |(_, icon)| material_index(icon))
}

async fn list(dir: &PathBuf) -> Entries {
    let mut entries = Vec::new();
    let Ok(mut reader) = tokio::fs::read_dir(dir).await else {
        return entries;
    };
    while let Ok(Some(entry)) = reader.next_entry().await {
        let name = entry.file_name().to_string_lossy().into_owned();
        if name == ".git" {
            continue;
        }
        let is_dir = entry.file_type().await.is_ok_and(|t| t.is_dir());
        entries.push((name, is_dir));
        if entries.len() >= MAX_ENTRIES {
            break;
        }
    }
    entries.sort_by(|a, b| {
        b.1.cmp(&a.1)
            .then_with(|| a.0.to_lowercase().cmp(&b.0.to_lowercase()))
    });
    entries
}

/// Breadth-first walk of `root`, returning workspace-relative paths with `/` separators.
async fn walk(root: &Path) -> Vec<String> {
    let mut files = Vec::new();
    let mut dirs = VecDeque::from([PathBuf::new()]);
    while let Some(rel) = dirs.pop_front() {
        let Ok(mut reader) = tokio::fs::read_dir(root.join(&rel)).await else {
            continue;
        };
        while let Ok(Some(entry)) = reader.next_entry().await {
            let name = entry.file_name().to_string_lossy().into_owned();
            let is_dir = entry.file_type().await.is_ok_and(|t| t.is_dir());
            let path = rel.join(&name);
            if is_dir {
                if !SKIP_DIRS.contains(&name.as_str()) {
                    dirs.push_back(path);
                }
            } else {
                files.push(path.to_string_lossy().replace('\\', "/"));
                if files.len() >= MAX_WALK {
                    return files;
                }
            }
        }
    }
    files
}

async fn write(path: &Path, contents: &str) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        tokio::fs::create_dir_all(parent)
            .await
            .map_err(|e| e.to_string())?;
    }
    tokio::fs::write(path, contents)
        .await
        .map_err(|e| e.to_string())
}

/// Serves file requests until the UI drops its sender.
pub async fn serve(mut requests: mpsc::UnboundedReceiver<FileReq>) {
    while let Some(request) = requests.recv().await {
        let posted = match request {
            FileReq::List(ListDir { dir, depth }) => {
                let entries = list(&dir).await;
                slint::invoke_from_event_loop(move || {
                    crate::bridge::files_listed(&dir, depth, entries);
                })
            }
            FileReq::Walk(root) => {
                let files = walk(&root).await;
                slint::invoke_from_event_loop(move || crate::chat::files_walked(files))
            }
            FileReq::Write { path, contents } => {
                let result = write(&path, &contents).await.map(|()| path);
                slint::invoke_from_event_loop(move || crate::chat::exported(result))
            }
        };
        if posted.is_err() {
            return;
        }
    }
}
